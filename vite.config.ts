  questions: "m05",
  sessions: "m05",
  /*
    M06's nouns are `interviews`, not `sessions`: M05 already owns that word
    here, and a shell that routes by noun would have sent every mock interview
    to the question bank. M06 renamed its own routes rather than take it.
  */
  agents: "m06",
  drills: "m06",
  interviews: "m06",
  calibration: "m13",
  disputes: "m13",
  ensembles: "m13",
  evaluations: "m13",
